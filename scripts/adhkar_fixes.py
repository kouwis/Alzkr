TAHLIL = "لاَ إِلَهَ إِلاَّ اللَّهُ، وَحْدَهُ لاَ شَرِيكَ لَهُ، لَهُ الْمُلْكُ وَلَهُ الْحَمْدُ وَهُوَ عَلَى كُلِّ شَيْءٍ قَدِيرٌ"


def _skel(t):
    import re
    return re.sub("[\u064B-\u065F\u0670\u0640\u060C:. ]", "", t)


def _n(t):
    import unicodedata
    return unicodedata.normalize("NFC", t)


def apply(sections):
    whole = {_n(k): v for k, v in WHOLE.items()}
    words = {_n(k): v for k, v in WORDS.items()}
    for sec in sections:
        for it in sec["items"]:
            for p in it["parts"]:
                t = p.get("t")
                if not t:
                    continue
                t = _n(t)
                key = t.strip()
                if key in whole:
                    new = whole[key]
                    # the letters must not change (only the vowel marks)
                    a = _skel(key).replace("إ", "ا").replace("أ", "ا").replace("آ", "ا")
                    b = _skel(new).replace("إ", "ا").replace("أ", "ا").replace("آ", "ا")
                    if a.replace("ى", "ي") != b.replace("ى", "ي") and "هذه" not in a and "للهرب" not in a and "إني" not in key:
                        print("adhkar fix changes letters:", key[:40], file=sys.stderr)
                    t = new
                for old, new in words.items():
                    t = t.replace(old, new)
                p["t"] = t
    # the morning's tahlil: once, ×100, with ×10 to choose
    for sec in sections:
        if sec["id"] != "morning":
            continue
        items = sec["items"]
        tahlil = [i for i, it in enumerate(items) if len(it["parts"]) == 1 and _skel(it["parts"][0].get("t", "")) == _skel(TAHLIL.replace("الْملْكُ", "الْمُلْكُ"))]
        ten = next((i for i in tahlil if items[i]["count"] == 10), None)
        hundred = next((i for i in tahlil if items[i]["count"] == 100), None)
        if ten is not None and hundred is not None:
            a, b = items[hundred], items[ten]
            a["alt"] = 10
            a["fadl"] = a.get("fadl", "") + " — " + b.get("fadl", "")
            del items[ten]
    return sections
